/* Video Models are Excellent Motion Models: project page behaviour.
   Clip lists come from static/js/data.js (generated by tools/build_assets.py). */
(function () {
  "use strict";

  var $ = function (s, r) { return (r || document).querySelector(s); };
  var $$ = function (s, r) { return Array.prototype.slice.call((r || document).querySelectorAll(s)); };
  var reduceMotion = window.matchMedia && matchMedia("(prefers-reduced-motion: reduce)").matches;
  var el = function (tag, cls, html) {
    var n = document.createElement(tag);
    if (cls) n.className = cls;
    if (html != null) n.innerHTML = html;
    return n;
  };
  var esc = function (s) { return String(s).replace(/[&<>"]/g, function (c) { return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]; }); };
  var play = function (v) { var p = v.play(); if (p) p.catch(function () {}); };

  /* ------------------------------------------------------------ theme */
  var root = document.documentElement;
  $("#themeBtn").addEventListener("click", function () {
    var next = root.getAttribute("data-theme") === "dark" ? "light" : "dark";
    root.setAttribute("data-theme", next);
    try { localStorage.setItem("v2m-theme", next); } catch (e) {}
  });
  if (window.matchMedia) {
    matchMedia("(prefers-color-scheme: light)").addEventListener("change", function (e) {
      var stored = null;
      try { stored = localStorage.getItem("v2m-theme"); } catch (err) {}
      if (!stored) root.setAttribute("data-theme", e.matches ? "light" : "dark");
    });
  }

  /* -------------------------------------------- nav, progress, scrollspy */
  var nav = $("#nav"), bar = $("#progress");
  var navLinks = $$(".navlinks a");
  var spySections = navLinks.map(function (a) { return $(a.getAttribute("href")); });
  var ticking = false;
  function onScroll() {
    ticking = false;
    var y = window.scrollY, h = document.documentElement.scrollHeight - innerHeight;
    nav.classList.toggle("scrolled", y > 24);
    bar.style.transform = "scaleX(" + (h > 0 ? Math.min(1, y / h) : 0) + ")";
    var current = -1, line = innerHeight * 0.35;
    spySections.forEach(function (s, i) { if (s && s.getBoundingClientRect().top < line) current = i; });
    navLinks.forEach(function (a, i) { a.classList.toggle("active", i === current); });
  }
  addEventListener("scroll", function () { if (!ticking) { ticking = true; requestAnimationFrame(onScroll); } }, { passive: true });
  onScroll();

  /* ------------------------------------------------------- scroll reveal */
  var revealIO = new IntersectionObserver(function (entries) {
    entries.forEach(function (e) {
      if (!e.isIntersecting) return;
      e.target.classList.add("in");
      revealIO.unobserve(e.target);
    });
  }, { rootMargin: "0px 0px -8% 0px", threshold: 0.06 });
  function observeReveal(n) {
    var sibs = $$(":scope > .reveal", n.parentElement);
    var i = sibs.indexOf(n);
    if (i > 0) n.style.transitionDelay = Math.min(i, 6) * 70 + "ms";
    revealIO.observe(n);
  }
  $$(".reveal").forEach(observeReveal);

  function whenSeen(node, fn, threshold) {
    var io = new IntersectionObserver(function (entries) {
      entries.forEach(function (e) { if (e.isIntersecting) { io.disconnect(); fn(); } });
    }, { threshold: threshold || 0.35 });
    io.observe(node);
  }

  /* ------------------------------------------------------------ count-up */
  $$("[data-count]").forEach(function (n) {
    var target = parseFloat(n.getAttribute("data-count"));
    var dec = parseInt(n.getAttribute("data-dec") || "0", 10);
    whenSeen(n, function () {
      if (reduceMotion) { n.textContent = target.toFixed(dec); return; }
      var t0 = performance.now(), dur = 1500;
      (function step(t) {
        var p = Math.min(1, (t - t0) / dur), e = 1 - Math.pow(1 - p, 4);
        n.textContent = (target * e).toFixed(dec);
        if (p < 1) requestAnimationFrame(step);
      })(t0);
    }, 0.6);
  });

  /* ------------------------------------------------------- hero wall video */
  var wall = $("#wallVideo");
  if (wall) {
    if (reduceMotion) { wall.removeAttribute("autoplay"); wall.pause(); }
    else new IntersectionObserver(function (es) {
      es.forEach(function (e) { if (e.isIntersecting) play(wall); else wall.pause(); });
    }).observe(wall);
  }

  /* ----------------------------------------------------- overview player */
  var teaser = $("#teaser"), tv = $("#teaserVideo");
  $("#teaserPlay").addEventListener("click", function () {
    tv.controls = true;
    teaser.classList.add("playing");
    tv.muted = false;
    play(tv);
  });

  /* -------------------------------------------------------------- lightbox
     Shows a figure (image) or a result clip (video, with prev/next). */
  var lb = $("#lightbox"), lbImg = $("#lbImg"), lbVid = $("#lbVid"), lbCap = $("#lbCap");
  var lbPrev = $("#lbPrev"), lbNext = $("#lbNext"), lastFocus = null, lbList = null, lbIdx = 0;
  function openLightbox() {
    if (lb.hidden) lastFocus = document.activeElement;
    lb.hidden = false;
    document.body.style.overflow = "hidden";
    $("#lbClose").focus();
  }
  function showImage(src, cap) {
    lbList = null;
    lbVid.pause(); lbVid.hidden = true; lbVid.removeAttribute("src");
    lbImg.hidden = false; lbImg.src = src; lbImg.alt = cap || "";
    lbCap.textContent = cap || "";
    lbPrev.hidden = lbNext.hidden = true;
    openLightbox();
  }
  function showClip(list, i) {
    lbList = list; lbIdx = (i + list.length) % list.length;
    var c = list[lbIdx];
    lbImg.hidden = true;
    lbVid.hidden = false; lbVid.muted = true; lbVid.src = c.src; play(lbVid);
    lbCap.textContent = c.prompt;
    lbPrev.hidden = lbNext.hidden = list.length < 2;
    openLightbox();
  }
  function closeLightbox() {
    lb.hidden = true;
    lbVid.pause(); lbVid.removeAttribute("src"); lbVid.load();
    document.body.style.overflow = "";
    if (lastFocus) lastFocus.focus();
  }
  document.addEventListener("click", function (e) {
    var z = e.target.closest("[data-zoom]");
    if (z) { e.preventDefault(); showImage(z.getAttribute("data-zoom"), z.getAttribute("data-cap")); }
  });
  $("#lbClose").addEventListener("click", closeLightbox);
  lbPrev.addEventListener("click", function () { showClip(lbList, lbIdx - 1); });
  lbNext.addEventListener("click", function () { showClip(lbList, lbIdx + 1); });
  lb.addEventListener("click", function (e) { if (e.target === lb || e.target.classList.contains("lb-fig")) closeLightbox(); });
  document.addEventListener("keydown", function (e) {
    if (lb.hidden) return;
    if (e.key === "Escape") closeLightbox();
    else if (lbList && e.key === "ArrowRight") showClip(lbList, lbIdx + 1);
    else if (lbList && e.key === "ArrowLeft") showClip(lbList, lbIdx - 1);
  });

  /* ----------------------------------------------- framework spotlight */
  var SPOTS = {
    all: null,
    A: [1.6, 10.6, 98.2, 24.6],
    B: [1.5, 36.2, 50.1, 60.0],
    C: [52.2, 36.2, 47.4, 63.4]
  };
  var FW_TEXT = {
    all: '<span class="c-v">Video model</span> &middot; <span class="c-m">Motion model</span> &middot; <span class="c-k">Keyframes</span> &rarr; one 22-joint skeleton',
    A: '<b>A</b> &nbsp;Text only, no guidance &nbsp; <span class="num v">1</span> vs <span class="num m">3</span>',
    B: '<b>B</b> &nbsp;Motion model in-betweens V2M keyframes &nbsp; <span class="num v">1</span> vs <span class="num m">2</span>',
    C: '<b>C</b> &nbsp;Video model enriches motion-model keyframes &nbsp; <span class="num m">3</span> vs <span class="num v">4</span>'
  };
  var fwFig = $("#fwFigure"), spot = $("#spot"), fwText = $("#fwText"), fwKey = "all";
  function placeSpot() {
    var r = SPOTS[fwKey], img = $("img", fwFig);
    if (!r) { spot.classList.remove("on"); return; }
    var pad = 6;
    spot.style.left = (img.offsetLeft + img.offsetWidth * r[0] / 100 - pad) + "px";
    spot.style.top = (img.offsetTop + img.offsetHeight * r[1] / 100 - pad) + "px";
    spot.style.width = (img.offsetWidth * r[2] / 100 + pad * 2) + "px";
    spot.style.height = (img.offsetHeight * r[3] / 100 + pad * 2) + "px";
    spot.classList.add("on");
  }
  function setFw(key) {
    fwKey = key;
    $$(".fw-tab").forEach(function (b) {
      var on = b.dataset.spot === key;
      b.classList.toggle("active", on);
      b.setAttribute("aria-selected", on ? "true" : "false");
    });
    fwText.innerHTML = FW_TEXT[key];
    fwText.classList.remove("swap"); void fwText.offsetWidth; fwText.classList.add("swap");
    placeSpot();
  }
  $$(".fw-tab").forEach(function (b) { b.addEventListener("click", function () { setFw(b.dataset.spot); }); });
  setFw("all");
  var fwImg = $("img", fwFig);
  if (fwImg.complete) placeSpot(); else fwImg.addEventListener("load", placeSpot);
  addEventListener("resize", placeSpot);

  /* ------------------------------------------------------- results gallery
     One tab per experiment; each shows a grid of looping clips. A clip only
     downloads when it nears the viewport and only plays while visible. */
  var EXPS = [
    { key: "A", title: "Text-only", desc: "Same prompt, no guidance.",
      legend: [["V2M (ours)", "--v2m", 1], ["Kimodo", "--kimodo"], ["MotionGPT3", "--mgpt"]] },
    { key: "B", title: "Video-to-Motion", desc: "Motion models in-between keyframes taken from V2M.",
      legend: [["V2M (ours)", "--v2m", 1], ["Kimodo", "--kimodo"], ["CondMDI", "--condmdi"], ["Keyframes", "--key"]] },
    { key: "C", title: "Motion-to-Video", desc: "Kimodo keyframes loosely guide the video model.",
      legend: [["V2M (ours)", "--v2m", 1], ["Kimodo (input)", "--kimodo"], ["Keyframes", "--key"]] },
    { key: "D", title: "Failure cases", fail: true, desc: "The video is right; lifting inverted poses to 3D fails.",
      legend: [["V2M (ours)", "--v2m", 1], ["Kimodo", "--kimodo"], ["MotionGPT3", "--mgpt"]] }
  ];
  var CLIPS = window.CLIPS || {};
  var gtabs = $("#gtabs"), gallery = $("#gallery"), gdesc = $("#gdesc"), glegend = $("#glegend");

  var loadIO = new IntersectionObserver(function (es) {
    es.forEach(function (e) {
      if (!e.isIntersecting) return;
      var v = e.target;
      if (!v.src && v.dataset.src) { v.src = v.dataset.src; }
      loadIO.unobserve(v);
    });
  }, { rootMargin: "300px 0px" });
  var playIO = new IntersectionObserver(function (es) {
    es.forEach(function (e) {
      var v = e.target;
      if (e.isIntersecting && !reduceMotion) { if (!v.src) v.src = v.dataset.src; play(v); }
      else v.pause();
    });
  }, { threshold: 0.35 });

  EXPS.forEach(function (x) {
    var b = el("button", "gtab" + (x.fail ? " fail" : ""));
    b.type = "button"; b.setAttribute("role", "tab"); b.dataset.exp = x.key;
    b.innerHTML = '<span class="xl">' + (x.fail ? "!" : x.key) + "</span>" + x.title +
      '<span class="cnt">' + (CLIPS[x.key] || []).length + "</span>";
    b.addEventListener("click", function () { showExp(x.key); });
    gtabs.appendChild(b);
  });

  function showExp(key) {
    var x = EXPS.filter(function (e) { return e.key === key; })[0];
    var list = CLIPS[key] || [];
    $$(".gtab", gtabs).forEach(function (b) {
      var on = b.dataset.exp === key;
      b.classList.toggle("active", on); b.setAttribute("aria-selected", on ? "true" : "false");
    });
    gdesc.textContent = x.desc;
    glegend.innerHTML = x.legend.map(function (l) {
      return '<span class="chip' + (l[2] ? " ours" : "") + '" style="--c:var(' + l[1] + ')"><i></i>' + esc(l[0]) + "</span>";
    }).join("");

    $$("video", gallery).forEach(function (v) { playIO.unobserve(v); loadIO.unobserve(v); v.pause(); v.removeAttribute("src"); v.load(); });
    gallery.innerHTML = "";
    gallery.classList.toggle("few", list.length < 3);
    list.forEach(function (c, i) {
      var tile = el("button", "tile");
      tile.type = "button";
      tile.setAttribute("aria-label", "Enlarge: " + c.prompt);
      tile.style.setProperty("--d", (i % 6) * 60 + "ms");
      tile.innerHTML = '<video muted loop playsinline preload="none" poster="' + c.poster + '" data-src="' + c.src + '"></video>' +
        '<span class="tile-zoom" aria-hidden="true"><svg width="15" height="15" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round"><path d="M15 3h6v6M9 21H3v-6M21 3l-7 7M3 21l7-7"/></svg></span>';
      tile.addEventListener("click", function () { showClip(list, i); });
      gallery.appendChild(tile);
      var v = $("video", tile);
      loadIO.observe(v); playIO.observe(v);
    });
    requestAnimationFrame(function () { gallery.classList.remove("enter"); void gallery.offsetWidth; gallery.classList.add("enter"); });
  }
  showExp("A");

  /* ------------------------------------------------------------ evaluation */
  var HUMAN = [
    { x: "A", name: "Text-only", rows: [["Naturalness", 72, 15, 13], ["Semantic alignment", 88, 7, 5], ["Fewer artifacts", 63, 25, 12]] },
    { x: "B", name: "Video-to-Motion", rows: [["Naturalness", 75, 14, 11], ["Semantic alignment", 74, 10, 16], ["Fewer artifacts", 72, 17, 11]] },
    { x: "C", name: "Motion-to-Video", rows: [["Naturalness", 61, 20, 19], ["Semantic alignment", 66, 16, 18], ["Fewer artifacts", 54, 31, 15]] }
  ];
  var COMPLETION = [["A", 86, 38], ["B", 84, 63], ["C", 86, 63]];
  var ORDER = [["A", 86, 45], ["B", 86, 69], ["C", 84, 66]];
  var VLM = [
    ["A", "Kimodo", "Common", [57.6, 36.4, 6.1], [57.6, 24.2, 18.2]],
    ["", "", "Complex", [59.4, 21.9, 18.8], [56.2, 25.0, 18.8]],
    ["", "M-GPT3", "Common", [39.4, 33.3, 27.3], [36.4, 33.3, 30.3]],
    ["", "", "Complex", [53.1, 25.0, 21.9], [53.1, 21.9, 25.0]],
    ["B", "Kimodo", "Common", [12.5, 81.2, 6.2], [12.5, 81.2, 6.2]],
    ["", "", "Complex", [12.5, 84.4, 3.1], [9.4, 87.5, 3.1]],
    ["", "CondMDI", "Common", [18.8, 68.8, 12.5], [15.6, 62.5, 21.9]],
    ["", "", "Complex", [12.5, 78.1, 9.4], [12.5, 78.1, 9.4]],
    ["C", "Kimodo", "Common", [46.4, 39.3, 14.3], [53.6, 28.6, 17.9]],
    ["", "", "Complex", [62.1, 20.7, 17.2], [58.6, 24.1, 17.2]]
  ];
  // contact %, jerk hands, feet, pelvis, ang. RMS, foot sliding
  var METRICS = [
    ["A", [["V2M (ours)", "--v2m", [44.15, 185.20, 90.55, 57.23, 466.80, 12.30]],
           ["Kimodo", "--kimodo", [72.77, 95.93, 80.90, 40.87, 1332.00, 6.19]],
           ["MotionGPT3", "--mgpt", [64.07, 108.90, 96.50, 36.78, 2608.00, 12.56]]]],
    ["B", [["V2M (ours)", "--v2m", [34.36, 231.70, 82.60, 70.24, 770.70, 7.47]],
           ["Kimodo", "--kimodo", [64.66, 151.30, 126.20, 78.60, 1724.00, 7.82]],
           ["CondMDI", "--condmdi", [55.78, 249.50, 205.30, 185.80, 1716.00, 17.07]]]],
    ["C", [["V2M (ours)", "--v2m", [41.06, 119.40, 80.54, 70.60, 351.40, 7.91]],
           ["Kimodo", "--kimodo", [85.68, 81.32, 97.79, 35.23, 982.50, 11.92]]]]
  ];

  function wtlBar(v, small, minLabel, dec) {
    var lbl = function (n) { return n >= (minLabel || 9) ? n.toFixed(dec || 0) + "%" : ""; };
    return '<div class="wtl' + (small ? " sm" : "") + '" role="img" aria-label="' + v[0] + "% wins, " + v[1] + "% ties, " + v[2] + '% losses">' +
      '<span class="w" data-w="' + v[0] + '">' + lbl(v[0]) + '</span><span class="t" data-w="' + v[1] + '">' + lbl(v[1]) +
      '</span><span class="l" data-w="' + v[2] + '">' + lbl(v[2]) + "</span></div>";
  }

  var hg = $("#humanGrid");
  HUMAN.forEach(function (h) {
    var card = el("div", "hcard");
    card.innerHTML = '<div class="hcard-head"><span class="xl">' + h.x + "</span><span>" + h.name + "</span></div>" +
      h.rows.map(function (r) {
        return '<div class="metric"><div class="metric-label"><span>' + r[0] + "</span><b>" + r[1] + "%</b></div>" + wtlBar(r.slice(1)) + "</div>";
      }).join("");
    hg.appendChild(card);
  });
  function pairs(target, data) {
    target.innerHTML = data.map(function (d) {
      return '<div class="pair"><span class="xl">' + d[0] + '</span>' +
        '<div class="pbar v"><span class="track"><i data-w="' + d[1] + '"></i></span><em>' + d[1] + "%</em></div>" +
        '<div class="pbar m"><span class="track"><i data-w="' + d[2] + '"></i></span><em>' + d[2] + "%</em></div></div>";
    }).join("") + '<div class="pairs-legend"><span><i style="background:var(--v2m)"></i>V2M</span><span><i style="background:var(--kimodo)"></i>Kimodo</span></div>';
  }
  pairs($("#compBars"), COMPLETION);
  pairs($("#orderBars"), ORDER);

  var vt = $("#vlmTable");
  vt.innerHTML = '<div class="vrow head"><span>Exp.</span><span>vs.</span><span>Group</span><span>Text alignment</span><span>Naturalness</span></div>' +
    VLM.map(function (r) {
      return '<div class="vrow' + (r[0] ? " first" : "") + '"><span class="vx">' + r[0] + "</span><span>" + r[1] + '</span><span class="vg">' + r[2] + "</span>" +
        '<div class="vbar-wrap" data-label="Text alignment">' + wtlBar(r[3], true, 11, 1) + '</div><div class="vbar-wrap" data-label="Naturalness">' + wtlBar(r[4], true, 11, 1) + "</div></div>";
    }).join("");

  var tb = $("#metricsTable tbody");
  METRICS.forEach(function (grp) {
    var rows = grp[1];
    var mins = [1, 2, 3, 4, 5].map(function (c) { return Math.min.apply(null, rows.map(function (r) { return r[2][c]; })); });
    rows.forEach(function (r, i) {
      var tr = el("tr", i === 0 ? "first ours" : "");
      tr.innerHTML = '<td class="exp">' + (i === 0 ? grp[0] : "") + '</td><td><span class="method-dot" style="--c:var(' + r[1] + ')"></span>' + r[0] + "</td>" +
        r[2].map(function (v, c) {
          var s = v.toFixed(2);
          return "<td>" + (c > 0 && v === mins[c - 1] ? "<b>" + s + "</b>" : s) + "</td>";
        }).join("");
      tb.appendChild(tr);
    });
  });

  function animateBars(scope) {
    $$("[data-w]", scope).forEach(function (n, i) {
      n.style.width = "0";
      setTimeout(function () { n.style.width = n.getAttribute("data-w") + "%"; }, 60 + (i % 9) * 40);
    });
  }
  var evalSeen = false;
  whenSeen($("#evaluation"), function () { evalSeen = true; animateBars($(".epane.active")); }, 0.15);
  $$(".etab").forEach(function (b) {
    b.addEventListener("click", function () {
      $$(".etab").forEach(function (o) {
        var on = o === b;
        o.classList.toggle("active", on); o.setAttribute("aria-selected", on ? "true" : "false");
      });
      $$(".epane").forEach(function (p) {
        var on = p.id === "pane-" + b.dataset.pane;
        p.hidden = !on; p.classList.toggle("active", on);
        if (on) { p.classList.add("in"); if (evalSeen) animateBars(p); }
      });
    });
  });

  /* ------------------------------------------------------------- BibTeX */
  $("#copyBib").addEventListener("click", function () {
    var btn = this, text = $("#bibtex").textContent;
    var done = function () {
      btn.classList.add("ok"); $("span", btn).textContent = "Copied";
      setTimeout(function () { btn.classList.remove("ok"); $("span", btn).textContent = "Copy"; }, 1800);
    };
    if (navigator.clipboard && navigator.clipboard.writeText) navigator.clipboard.writeText(text).then(done, fallback);
    else fallback();
    function fallback() {
      var r = document.createRange(); r.selectNodeContents($("#bibtex"));
      var s = getSelection(); s.removeAllRanges(); s.addRange(r);
      try { document.execCommand("copy"); done(); } catch (e) {}
    }
  });
})();
